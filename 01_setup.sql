--Creation of the table production order
CREATE TABLE PRODUCTIONORDER (
    CODE NVARCHAR(50) PRIMARY KEY,
    MATERIAL NVARCHAR(50) NOT NULL,
    WIDTHMM INT NOT NULL,
    REQUIREDROLLS INT NOT NULL,
    NOMINALROLLWEIGHTKG DECIMAL(18,3) NOT NULL,
    ISONHOLD BIT NOT NULL DEFAULT 0
);

--Creation of the table production report
CREATE TABLE PRODUCTIONREPORT (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ORDERCODE NVARCHAR(50) FOREIGN KEY REFERENCES PRODUCTIONORDER(CODE),
    GOODROLLS INT NOT NULL,
    NONCONFORMINGROLLS INT NOT NULL,
    DEFECTNOTE NVARCHAR(250) NULL,
    CREATEDUTC DATETIME2 DEFAULT SYSUTCDATETIME()
);
GO

